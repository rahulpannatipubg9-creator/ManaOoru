def category_to_kind(cat: str) -> str:
    c = cat.lower()
    if "flower" in c: return "flowers"
    if "milk" in c or "dairy" in c: return "dairy"
    if "footwear" in c or "shoe" in c: return "shoes"
    if "dress" in c or "cloth" in c or "wear" in c or "tailor" in c or "saree" in c: return "clothes"
    if "dosa" in c or "tiffin" in c or "idli" in c or "mess" in c: return "restaurant"
    if "restaurant" in c or "mandi" in c or "biryani" in c or "fast food" in c or "food" in c: return "restaurant"
    if "kirana" in c or "supermarket" in c or "grocery" in c or "store" in c: return "supermarket"
    if "pharmacy" in c or "medical" in c: return "chemist"
    if "chicken" in c or "mutton" in c or "butcher" in c: return "butcher"
    if "lock" in c: return "hardware"
    if "tea" in c or "cafe" in c or "soda" in c: return "cafe"
    if "complex" in c or "poi" in c: return "commercial"
    return "shop"

def process_survey():
    catalog_shops = []
    provisional_placements = []

    for item in RAW_SHOPS:
        entry = dict(item)
        lat = entry.get("latitude")
        lon = entry.get("longitude")
        if lat is not None and lon is not None:
            gx, gz = lon_lat_to_godot(lon, lat)
            entry["godot_coord"] = {"x": gx, "y": 0.0, "z": gz}
            entry["playable_radius_ok"] = math.hypot(gx, gz) <= 3000.0
            
            # Category to standard kind
            kind = category_to_kind(entry["category"])
            provisional_placements.append({
                "shop_id": entry["shop_id"],
                "name": entry["name"],
                "lat": lat,
                "lon": lon,
                "kind": kind,
                "godot_x": gx,
                "godot_z": gz,
                "zone": entry["zone"],
                "category": entry["category"],
                "source": entry.get("source_url", "Field survey catalog")
            })
        else:
            entry["godot_coord"] = None
            entry["playable_radius_ok"] = False
        
        catalog_shops.append(entry)

    catalog_data = {
        "metadata": {
            "title": "Godavarikhani Commercial Directory & Field Survey Catalog",
            "date": "2026-10-31",
            "total_zones": len(ZONES),
            "total_shops": len(catalog_shops),
            "shops_with_coordinates": len(provisional_placements),
            "shops_requiring_ground_survey": len(catalog_shops) - len(provisional_placements)
        },
        "zones": ZONES,
        "shops": catalog_shops
    }

    # 1. Write full survey catalog
    survey_path = Path("data/survey/godavarikhani_survey_catalog.json")
    survey_path.parent.mkdir(parents=True, exist_ok=True)
    survey_path.write_text(json.dumps(catalog_data, indent=2, ensure_ascii=False))
    print(f"Saved {survey_path} with {len(catalog_shops)} surveyed shops.")

    # 2. Update user_shop_labels.json
    labels_path = Path("data/local/user_shop_labels.json")
    existing_data = {"shops": []}
    if labels_path.exists():
        try:
            existing_data = json.loads(labels_path.read_text())
        except Exception:
            pass

    existing_names = {s.get("name", "").strip().lower() for s in existing_data.get("shops", [])}
    added_count = 0

    for prov in provisional_placements:
        name_clean = prov["name"].strip()
        if name_clean.lower() not in existing_names:
            existing_data["shops"].append({
                "shop_id": prov["shop_id"],
                "name": name_clean,
                "lat": prov["lat"],
                "lon": prov["lon"],
                "kind": prov["kind"],
                "source": prov["source"],
                "zone": prov["zone"]
            })
            existing_names.add(name_clean.lower())
            added_count += 1

    labels_path.write_text(json.dumps(existing_data, indent=2, ensure_ascii=False))
    print(f"Updated {labels_path} with {added_count} new provisional shops (Total: {len(existing_data['shops'])}).")

if __name__ == "__main__":
    process_survey()
